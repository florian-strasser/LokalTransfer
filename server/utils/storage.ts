import { promises as fs } from 'node:fs'
import { isAbsolute, join, resolve, sep } from 'node:path'
import { randomBytes } from 'node:crypto'
import type { H3Event } from 'h3'
import { logger } from './logger'

// Where uploaded files live on disk.
//
// The storage root is deliberately outside `public/`: nothing under it is served
// statically, so a file is only ever reachable through the download handler,
// which checks the transfer's token and expiry first. Putting uploads in
// `public/` would make every file world-readable to anyone who guessed the path,
// and would quietly outlive the expiry rules.
//
// Layout is one directory per transfer:
//   <root>/transfers/<transfer id>/<random stored name>
// which makes deleting an expired transfer a single recursive remove, and means
// a stray file can always be traced back to a row.

/** Absolute path of the storage root, resolved from runtimeConfig. */
export function storageRoot(event?: H3Event): string {
  const config = useRuntimeConfig(event)
  const configured = String(config.storagePath || './storage')
  // A relative path is resolved against the working directory, which is the
  // project root in dev and the deployment directory in production.
  return isAbsolute(configured) ? configured : resolve(process.cwd(), configured)
}

/** Absolute path of one transfer's directory. */
export function transferDir(transferId: number, event?: H3Event): string {
  return join(storageRoot(event), 'transfers', String(transferId))
}

/** Create a transfer's directory if it doesn't exist yet. */
export async function ensureTransferDir(transferId: number, event?: H3Event): Promise<string> {
  const dir = transferDir(transferId, event)
  await fs.mkdir(dir, { recursive: true })
  return dir
}

/**
 * Generate the on-disk name for an upload.
 *
 * The original filename never touches the filesystem — it is kept in the
 * database and only reattached in the `Content-Disposition` header on the way
 * out. That removes path traversal, reserved Windows names, unicode
 * normalisation collisions and case-insensitive overwrites as a class of
 * problem, rather than trying to sanitise them one by one.
 */
export function generateStoredName(): string {
  return randomBytes(24).toString('hex')
}

/**
 * Resolve a stored file to an absolute path, refusing anything that escapes its
 * transfer's directory.
 *
 * Stored names are generated by this module, so a traversal attempt would mean
 * the database itself was tampered with. The check costs nothing and turns that
 * from an arbitrary file read into a 404.
 */
export function resolveStoredFile(
  transferId: number,
  storedName: string,
  event?: H3Event
): string | null {
  const dir = transferDir(transferId, event)
  const full = resolve(dir, storedName)

  // The trailing separator matters: without it, `/storage/transfers/1extra`
  // would pass a plain `startsWith('/storage/transfers/1')` check.
  if (full !== dir && !full.startsWith(dir + sep)) {
    logger.warn('Rejected stored file path outside its transfer directory', {
      transferId,
      storedName
    })
    return null
  }

  return full
}

/** Remove a transfer's directory and everything in it. Safe to call twice. */
export async function removeTransferDir(transferId: number, event?: H3Event): Promise<void> {
  const dir = transferDir(transferId, event)
  try {
    await fs.rm(dir, { recursive: true, force: true })
  } catch (error) {
    // Logged rather than thrown: cleanup runs over many transfers, and one
    // undeletable directory shouldn't stop the rest from being processed.
    logger.error('Failed to remove transfer directory', { dir, error })
  }
}

/** Delete a single stored file, ignoring the case where it is already gone. */
export async function removeStoredFile(
  transferId: number,
  storedName: string,
  event?: H3Event
): Promise<void> {
  const full = resolveStoredFile(transferId, storedName, event)
  if (!full) return

  try {
    await fs.unlink(full)
  } catch (error) {
    // A file that is already gone is the expected case when a sweep is retried.
    if ((error as NodeJS.ErrnoException)?.code !== 'ENOENT') {
      logger.error('Failed to remove stored file', { full, error })
    }
  }
}

/** Whether a stored file is actually present on disk. */
export async function storedFileExists(
  transferId: number,
  storedName: string,
  event?: H3Event
): Promise<boolean> {
  const full = resolveStoredFile(transferId, storedName, event)
  if (!full) return false

  try {
    const stats = await fs.stat(full)
    return stats.isFile()
  } catch {
    return false
  }
}

// A member's own files — today only their default background — live apart from
// the transfers, one directory per user:
//   <root>/users/<user id>/<random stored name>
// The cleanup task's orphan sweep only ever looks inside <root>/transfers, so
// nothing here can be mistaken for the residue of a deleted transfer.

// User ids are generated by the app, but a path built from one is still checked:
// an id of `..` would otherwise put the directory at the storage root itself.
const SAFE_USER_ID = /^[\w-]{1,64}$/

/** Absolute path of one user's directory, or null for an id unsafe in a path. */
export function userDir(userId: string, event?: H3Event): string | null {
  if (!SAFE_USER_ID.test(userId)) return null
  return join(storageRoot(event), 'users', userId)
}

/**
 * Resolve a file in a user's directory, refusing anything that escapes it —
 * the same guard as `resolveStoredFile`, for the same reason.
 */
export function resolveUserFile(userId: string, storedName: string, event?: H3Event): string | null {
  const dir = userDir(userId, event)
  if (!dir) return null

  const full = resolve(dir, storedName)
  if (full === dir || !full.startsWith(dir + sep)) {
    logger.warn('Rejected stored file path outside its user directory', { userId, storedName })
    return null
  }

  return full
}

/** Delete one file from a user's directory, ignoring the case where it is already gone. */
export async function removeUserFile(userId: string, storedName: string, event?: H3Event): Promise<void> {
  const full = resolveUserFile(userId, storedName, event)
  if (!full) return

  try {
    await fs.unlink(full)
  } catch (error) {
    if ((error as NodeJS.ErrnoException)?.code !== 'ENOENT') {
      logger.error('Failed to remove user file', { full, error })
    }
  }
}

/** Remove a user's directory and everything in it. Safe to call twice. */
export async function removeUserDir(userId: string, event?: H3Event): Promise<void> {
  const dir = userDir(userId, event)
  if (!dir) return

  try {
    await fs.rm(dir, { recursive: true, force: true })
  } catch (error) {
    logger.error('Failed to remove user directory', { dir, error })
  }
}
